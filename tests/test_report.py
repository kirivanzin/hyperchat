"""The published report, and the test that stops it becoming the file this repo refuses to commit.

`evals/results.jsonl` is gitignored because a committed results file is a score from an old model
reported as today's. `docs/eval-report.md` is that file with better formatting unless something
notices it going stale, so: the three hashes in the page must equal the current ones, and the README
line must agree with the page. Change the prompt, the corpus or a limit, and the suite fails until
`make report` is run again — every prompt edit becomes `make report && git add`, which is the price of
publishing numbers at all.
"""

from __future__ import annotations

import importlib.util
import json
import re
import sys
from pathlib import Path
from types import ModuleType

from hyperchat import configuration

REPO = Path(__file__).resolve().parents[1]
REPORT = REPO / "docs" / "eval-report.md"
README = REPO / "README.md"


def load_harness() -> ModuleType:
    spec = importlib.util.spec_from_file_location(
        "eval_harness_report", REPO / "scripts" / "eval.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


harness = load_harness()


def report_text() -> str:
    assert REPORT.is_file(), "docs/eval-report.md is missing; run `make report`"
    return REPORT.read_text()


def reported_block() -> dict[str, str]:
    match = re.search(r"^eval config (.*)$", report_text(), re.MULTILINE)
    assert match, "the report has no configuration line"
    return configuration.parse("config " + match.group(1))


def readme_line() -> str:
    match = re.search(r"^\*\*Latest eval:\*\* (.*)$", README.read_text(), re.MULTILINE)
    assert match, "README has no 'Latest eval' line; run `make report`"
    return match.group(1)


def test_the_report_is_current():
    """The three hashes say whether this page still describes the code."""
    block = configuration.resolved()
    reported = reported_block()

    assert reported["prompt_sha256"] == block.prompt_sha256, "the prompt moved: run `make report`"
    assert reported["corpus_sha256"] == block.corpus_sha256, "the corpus moved: run `make report`"
    assert reported["config_sha256"] == block.sha256(), "a limit moved: run `make report`"


def test_the_readme_line_is_generated_from_the_same_run():
    """The first thing a skimming reader meets, and the first thing to rot."""
    line = readme_line()
    page = report_text()

    decided = re.search(r"\| decided \| \*\*(\d+)/(\d+)\*\* \|", page)
    assert decided, "the report has no decided row"
    assert f"{decided.group(1)}/{decided.group(2)} decided" in line

    injection = re.search(r"\| injection \| \*\*(\d+)/(\d+)\*\* \(floor (\d+)\) \|", page)
    assert injection, "the report has no injection row"
    assert f"injection {injection.group(1)}/{injection.group(2)}" in line
    assert f"(floor {injection.group(3)})" in line

    p95_ms = int(re.search(r"p95 (\d+) ms", page).group(1))
    assert f"p95 {p95_ms / 1000:.1f} s" in line

    total = int(re.search(r"total ([\d,]+) ·", page).group(1).replace(",", ""))
    assert f"~{round(total / 1000)} k tokens" in line

    assert re.search(r"`[0-9a-f]{7,}`", line), "the line names no commit"
    assert "(docs/eval-report.md)" in line


def test_the_report_says_it_is_generated_and_dated():
    page = report_text()
    assert "Generated by `make report`" in page
    assert "Do not edit" in page
    assert re.search(r"at commit `[0-9a-f]{7,}`", page)
    assert "baseline, not a benchmark" in page


def test_a_model_with_no_rate_is_reported_as_tokens_only():
    """A dollar figure needs a model, a rate and a date; inventing the row is how a report lies."""
    block = configuration.resolved()
    table = {"read": "2026-01-01", "models": {"some-other-model": {"prompt": 1, "completion": 2}}}

    line = harness.cost({"prompt": 1000, "completion": 1000, "total": 2000}, block, table)

    assert line.startswith(f"no rate on file for {block.model}")
    assert "2026-01-01" in line
    assert "$" not in line


def test_a_priced_model_multiplies_the_tokens_by_the_rate():
    block = configuration.resolved()
    table = {
        "read": "2026-11-13",
        "currency": "USD",
        "per_tokens": 1_000_000,
        "models": {block.model: {"prompt": 0.3, "completion": 1.2}},
    }

    line = harness.cost(
        {"prompt": 1_000_000, "completion": 1_000_000, "total": 2_000_000}, block, table
    )

    assert "USD 1.5000" in line
    assert "read 2026-11-13" in line


def test_the_rate_table_has_a_date_and_a_source():
    table = json.loads((REPO / "evals" / "rates.json").read_text())
    assert table["read"] == "2026-11-13"
    assert table["source"].startswith("https://")
    assert table["models"], "a table with no models can never state a cost"


def test_the_generated_readme_line_does_not_move_the_corpus(monkeypatch, tmp_path):
    """The page and the corpus contain each other otherwise: the line is a pointer, not documentation."""
    from hyperchat import corpus

    monkeypatch.setattr(corpus, "ROOT", tmp_path)
    monkeypatch.setattr(corpus, "DOCUMENTS", {"README.md": "the readme"})

    # The shape after a first `make report`: the marker line is there, and regeneration replaces it
    # in place. Its contents must not matter.
    (tmp_path / "README.md").write_text("# readme\n\n**Latest eval:** 0/0 decided\n\nsome prose\n")
    before = corpus.corpus_sha256()

    (tmp_path / "README.md").write_text(
        "# readme\n\n**Latest eval:** 20/20 decided · p95 1.4 s\n\nsome prose\n"
    )
    assert corpus.corpus_sha256() == before, "regenerating the line moved the corpus hash"

    (tmp_path / "README.md").write_text(
        "# readme\n\n**Latest eval:** 20/20 decided · p95 1.4 s\n\nsome *changed* prose\n"
    )
    assert corpus.corpus_sha256() != before, "a real documentation change must move the hash"
